import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Preserve module-worker relative imports and notices outside the Next bundler. */
export function prepareMapWorker() {
  const packageRoot = dirname(fileURLToPath(import.meta.resolve('maplibre-gl/package.json')));
  const { version } = JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8'));
  const root = fileURLToPath(new URL('..', import.meta.url));
  const output = join(root, 'apps/web/public/vendor/maplibre-gl', version);
  mkdirSync(output, { recursive: true });
  for (const name of ['maplibre-gl-worker.mjs', 'maplibre-gl-shared.mjs']) copyFileSync(join(packageRoot, 'dist', name), join(output, name));
  copyFileSync(join(packageRoot, 'LICENSE.txt'), join(output, 'LICENSE.txt'));
  // MapLibre's stylesheet, wrapped in the `vendor` cascade layer so the site's layered styles can restyle map controls
  // without !important (unlayered CSS would otherwise beat every layer). Rewritten only when the library changes.
  const css = `/* maplibre-gl ${version} dist/maplibre-gl.css, BSD-3-Clause; generated by scripts/prepare-map-worker.mjs */\n@layer reset, tokens, vendor, base, components, layout, pages, utilities;\n@layer vendor {\n${readFileSync(join(packageRoot, 'dist/maplibre-gl.css'), 'utf8').trim()}\n}\n`;
  const target = join(root, 'apps/web/generated/maplibre.css');
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
  if (current !== css) writeFileSync(target, css);
  console.log(`Prepared local MapLibre ${version} worker and license.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) prepareMapWorker();
